#pragma once

#define TCPP03_I2C_TIMEOUT 50

#define TCPP03_REG_CONTROL 0x00
#define TCPP03_REG_ACK     0x01
#define TCPP03_REG_FLAGS   0x02

#define TCPP03_CONTROL_GDP_CLOSED           (1 << 2)
#define TCPP03_CONTROL_GDC_OPEN             (1 << 3)
#define TCPP03_CONTROL_PM1                  (1 << 4)
#define TCPP03_CONTROL_PM2                  (1 << 5)
#define TCPP03_CONTROL_POWER_MODE_MASK      (TCPP03_CONTROL_PM2 | TCPP03_CONTROL_PM1)
#define TCPP03_CONTROL_POWER_MODE_HIBERNATE 0
#define TCPP03_CONTROL_POWER_MODE_LOW_POWER TCPP03_CONTROL_PM2
#define TCPP03_CONTROL_POWER_MODE_NORMAL    TCPP03_CONTROL_PM1
#define TCPP03_CONTROL_VBUS_DISCHARGE       (1 << 6)

#define TCPP03_FLAGS_MASK          0x3F
#define TCPP03_FLAGS_DEVICE_TCPP02 (1 << 7)
